const DICT: Record<AppLang, Record<string, string>> = { zh, en }

export type I18nKey = keyof typeof zh

/** 翻译核心：{0}{1} 为参数占位。组件外（store 等）用 translate，组件内用 useT */
export function translate(lang: AppLang, key: I18nKey, ...args: string[]): string {
  let text = DICT[lang][key] ?? DICT.zh[key] ?? key
  args.forEach((arg, i) => {
    text = text.replace(`{${i}}`, arg)
  })
  return text
}

/** 界面文案 hook：返回 t(key, ...args)，语言切换时触发重渲染 */
export function useT(): (key: I18nKey, ...args: string[]) => string {
  const lang = useUIStore((s) => s.lang)
  return (key, ...args) => translate(lang, key, ...args)
}
